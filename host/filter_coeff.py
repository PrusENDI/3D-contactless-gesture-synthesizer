"""Generate ``rtl/v2_filter_coeffs.sv``, the ladder's coefficient BSRAM (P2a).

The table is defined in ``docs/superpowers/specs/2026-11-01-filter-lfo-design.md``
5.3 and laid out as one 1024x16 memory:

    addr   0.. 511  G[ci]    TPT one-pole coefficient, Q16
                             G = round(65536 * q/(1+q)), q = tan(pi*fc/fs),
                             fc = 40 Hz * 2**(ci/48), ci clamped to 423
                             (511 entries used: fc stops at ~18 kHz)
    addr 512.. 767  R[idx]   1/(1+x), Q16, x = (idx-512)*0.94/255
                             x = K*G^4 in [0, 0.93], so [0, 0.94] covers it
    addr 768..1023  reserved, tied to 0 (the LFO sine is a polynomial)

The read port is registered, so a consumer gets ``dout`` one clock after ``addr``.

    python host/filter_coeff.py --emit        # rewrite rtl/v2_filter_coeffs.sv
"""

import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SV_PATH = os.path.join(os.path.dirname(HERE), "rtl", "v2_filter_coeffs.sv")

FS = 48000.0
CI_MAX = 423
G_COUNT = 512
R_BASE = 512
R_COUNT = 256
MEM_DEPTH = 1024
R_X_SPAN = 0.94


def q16(value):
    """Round to 16-bit Q16, half away from zero (the table's rounding rule)."""
    return int(math.floor(value + 0.5))


def fc_of(ci):
    return 40.0 * 2.0 ** (max(0, min(int(ci), CI_MAX)) / 48.0)


def g_value(ci):
    """G[ci] in Q16; every ci above 423 repeats the ci=423 value."""
    q = math.tan(math.pi * fc_of(ci) / FS)
    return q16(65536.0 * q / (1.0 + q))


def g_table():
    return [g_value(ci) for ci in range(G_COUNT)]


def r_value(ridx):
    """R[ridx] in Q16: 1/(1+x) with x spanning [0, 0.94] over 256 entries."""
    return q16(65536.0 / (1.0 + ridx * R_X_SPAN / (R_COUNT - 1)))


def r_table():
    return [r_value(ridx) for ridx in range(R_COUNT)]


HEADER = """\
// GENERATED FILE -- DO NOT EDIT BY HAND.
// Generated by host/filter_coeff.py --emit from
// docs/superpowers/specs/2026-11-01-filter-lfo-design.md 5.3.
//
//   addr   0.. 511 : G[ci]   TPT one-pole coefficient, Q16
//                             G = round(65536*q/(1+q)), q = tan(pi*fc/fs),
//                             fc = 40 Hz * 2**(ci/48), ci clamped to 423.
//   addr 512.. 767 : R[idx]  1/(1+x) as Q16, x = (idx-512)*0.94/255,
//                             covering x = K*G^4 in [0, 0.93].
//   addr 768..1023 : reserved, tied to 0 (the LFO sine is a polynomial).
//
// R[0] is 1.0 exactly, which does not fit a 16-bit word: it is stored as
// 0xFFFF (0.99998, a 0.0002 dB error) like every other entry is rounded.
//
// The read port is registered: dout shows mem[addr] one clock after addr.
// This file must not be edited by hand -- change the generator and re-run
// "python host/filter_coeff.py --emit".
"""


def emit_source():
    """Return the full text of rtl/v2_filter_coeffs.sv (LF line endings)."""
    out = [HEADER]
    out.append("module v2_filter_coeffs (")
    out.append("        input  logic        clk,")
    out.append("        input  logic [9:0]  addr,")
    out.append("        output logic [15:0] dout")
    out.append(");")
    out.append("")
    out.append("    localparam int R_BASE = %d;" % R_BASE)
    out.append("")
    out.append("    logic [15:0] mem [0:%d];" % (MEM_DEPTH - 1))
    out.append("")
    out.append("    // One registered port: dout is valid one clock after addr.")
    out.append("    always_ff @(posedge clk) dout <= mem[addr];")
    out.append("")
    out.append("    // Coefficient image.  Gowin infers a BSRAM from this initial block;")
    out.append("    // if a build ever reports it as LUTs, see the plan's Task 7 fallback.")
    out.append("    initial begin")
    rows = g_table() + r_table()
    for index in range(MEM_DEPTH):
        value = rows[index] if index < len(rows) else 0
        out.append("        mem[%4d] = 16'h%04x;" % (index, min(value, 0xFFFF)))
    out.append("    end")
    out.append("")
    out.append("endmodule")
    out.append("")
    return "\n".join(out)


def write_source(path=SV_PATH):
    text = emit_source()
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return text


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate rtl/v2_filter_coeffs.sv.")
    ap.add_argument("--emit", action="store_true", help="rewrite rtl/v2_filter_coeffs.sv")
    args = ap.parse_args(argv)
    if args.emit:
        text = write_source()
        print("wrote %s (%d words, %d lines)"
              % (os.path.relpath(SV_PATH).replace("\\", "/"),
                 MEM_DEPTH, text.count("\n")))
        return 0
    ap.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
