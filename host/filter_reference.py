"""Float gold model for the 24 dB/oct ZDF ladder low-pass (P2a).

Mirrors ``docs/superpowers/specs/2026-11-01-filter-lfo-design.md`` 5.2.  One
stage is a TPT (trapezoidal / bilinear) one-pole:

    v_i = G (u_i - s_i)      y_i = v_i + s_i      s_i <- y_i + v_i

Four stages in series plus a zero-delay-feedback solve:

    y4 = G^4 u + S           S = (1-G) (G^3 s1 + G^2 s2 + G s3 + s4)
    u  = (x - K S) / (1 + K G^4)          K = res * 3.75 / 256

Steady state makes the whole thing linear, so the loop collapses to

    H(z) = H1(z)^4 / (1 + K H1(z)^4)
    H1(z) = G (1 + z^-1) / (1 - (1 - 2G) z^-1)

with ``G = q/(1+q)``, ``q = tan(pi fc / fs)``, ``fc = 40 Hz * 2**(ci/48)``.
That is what :func:`ladder_db` evaluates, and it is why ``Kcrit = 4`` is
independent of the cutoff: |H1^4| = 1/4 at exactly 180 degrees of loop phase,
at the design fc of every stage, for every ci.

The model is deliberately float and standard-library only (``cmath``, ``math``)
so it cannot share a bug with the fixed-point RTL it is used to check.

    python host/filter_reference.py --emit-tb
"""

import argparse
import cmath
import math
import sys

FS = 48000.0
CI_MAX = 423
K_MAX = 3.75          # K = res*K_MAX/256, so Kcrit=4 is never reached
RES_FULL = 256.0
_F_LO = 1.0           # below this the response is within 0.05 dB of DC
_F_HI = 0.49 * FS


def ci_fc(ci):
    """Design cutoff of one pole; ci is 1/48 octave, clamped to [0, 423]."""
    ci = max(0, min(int(round(ci)), CI_MAX))
    return 40.0 * 2.0 ** (ci / 48.0)


def tpt_pole(fc, fs=FS):
    """TPT one-pole coefficient G = q/(1+q)."""
    q = math.tan(math.pi * fc / fs)
    return q / (1.0 + q)


def _pole_response(g, freq, fs=FS):
    """H1(e^jw) of one TPT pole; H1(0) = 1, H1(Nyquist) = 0."""
    zi = cmath.exp(-2j * math.pi * freq / fs)
    return g * (1.0 + zi) / (1.0 - (1.0 - 2.0 * g) * zi)


def ladder_response(ci, res, freq, fs=FS):
    """Complex response of the closed-loop 4-pole at ``freq`` at res=0..255."""
    k = res * K_MAX / RES_FULL
    h = _pole_response(tpt_pole(ci_fc(ci), fs), freq, fs) ** 4
    return h / (1.0 + k * h)


def ladder_db(ci, res, freq, fs=FS):
    """Gain in dB at ``freq``; res=0 gives the plain 24 dB/oct rolloff."""
    mag = abs(ladder_response(ci, res, freq, fs))
    return 20.0 * math.log10(max(mag, 1e-30))


def minus3db(ci):
    """-3 dB point at res=0, the column the spec measured (18 Hz .. 12.3 kHz)."""
    if ladder_db(ci, 0, _F_LO) <= -3.0:
        raise ValueError("ci=%r: response already below -3 dB at %.3f Hz" % (ci, _F_LO))
    if ladder_db(ci, 0, _F_HI) >= -3.0:
        raise ValueError("ci=%r: response still above -3 dB at %.1f Hz" % (ci, _F_HI))
    lo, hi = _F_LO, _F_HI
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        if ladder_db(ci, 0, mid) > -3.0:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def peak_freq(ci, res, n=4096):
    """Frequency of the gain maximum, log-swept then refined by a ternary search."""
    if res == 0:
        return _F_LO
    ratio = (_F_HI / _F_LO) ** (1.0 / (n - 1))
    best_f, best_db = _F_LO, -1e9
    freq = _F_LO
    for _ in range(n):
        db = ladder_db(ci, res, freq)
        if db > best_db:
            best_f, best_db = freq, db
        freq *= ratio
    lo, hi = best_f / ratio, best_f * ratio
    for _ in range(80):
        a = lo + (hi - lo) / 3.0
        b = hi - (hi - lo) / 3.0
        if ladder_db(ci, res, a) < ladder_db(ci, res, b):
            lo = a
        else:
            hi = b
    return 0.5 * (lo + hi)


def dc_db(ci, res):
    """Passband gain: 1/(1+K).  The plain ladder loses level as K rises --
    exactly the droop a Moog shines through.  Not monotone in the peak."""
    return 20.0 * math.log10(1.0 / (1.0 + res * K_MAX / RES_FULL))


def peak_db(ci, res):
    """Gain maximum in dB (absolute, as the spec 5.3 peak column is).  K=3.75
    peaks near +14.7 dB at any ci.  Because DC drops by 1/(1+K), this value is
    non-monotone in res at low res; use peak_db - dc_db for the resonance itself.
    """
    if res == 0:
        return ladder_db(ci, 0, _F_LO)
    return ladder_db(ci, res, peak_freq(ci, res))


def emit_tb():
    """SystemVerilog constants for Task 5's testbench (paste-ready, ASCII)."""
    lines = []
    lines.append("// --- v2_ladder_lp test constants -------------------------------")
    lines.append("// Generated by host/filter_reference.py --emit-tb (float gold model,")
    lines.append("// spec 5.2-5.3).  Do not hand-edit: regenerate instead.")
    lines.append("// 4-pole -3 dB point at res=0:")
    for ci in (96, 192, 288):
        lines.append("localparam real F_MINUS3DB_CI%d_HZ = %.1f;  // %.0f Hz one-pole fc"
                     % (ci, minus3db(ci), ci_fc(ci)))
    lines.append("// Peak gain at res=255 (K=3.75); spec 5.2 expects +14.0..+15.2 dB:")
    for ci in (48, 192, 336):
        lines.append("localparam real PEAK_DB_CI%d_RES255 = %.2f;  // at %.0f Hz"
                     % (ci, peak_db(ci, 255), peak_freq(ci, 255)))
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Float gold model for the P2a ladder low-pass.")
    ap.add_argument("--emit-tb", action="store_true",
                    help="print the SV constants Task 5 pastes into tb_filter_ladder.sv")
    args = ap.parse_args(argv)
    if args.emit_tb:
        sys.stdout.write(emit_tb())
        return 0
    ap.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
