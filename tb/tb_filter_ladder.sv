`timescale 1ns/1ps
// Unit test for the 24 dB/oct ZDF ladder low-pass (plan task 5).
//
// The seven claims of the plan's task 5 step 1, in order: one-sample latency,
// the three -3 dB points at res=0, resonance monotone above DC, resonance
// uniform in cutoff, no divergence over the whole ci x res range, saturation
// without wrap, and that nothing moves except on sample_ce.
//
// Time base.  sample_ce is one clock wide every 20 clocks.  The clock period is
// irrelevant to the numbers: the input samples are synthesised as if the sample
// rate were exactly 48 kHz, because that is what the coefficient table bakes in.
// A 1 kHz test tone is sin(2*pi*1000*n/48000) whatever the clock does.
//
// Frequencies are measured by driving a steady sine and taking the peak of the
// settled output; the -3 dB point is found by bisection on that measurement.
// The resonance is measured as peak_db minus the theoretical passband droop
// 20*log10(1/(1+K)) (host/filter_reference.py dc_db), because the absolute peak
// is NOT monotone in res: the ladder loses 1/(1+K) of its DC gain as K rises.

module tb_filter_ladder;

  localparam int  CEP = 20;                        // clocks per sample_ce (1667 available)
  localparam real FS  = 48000.0;
  localparam real PI  = 3.141592653589793;

  // --- v2_ladder_lp test constants -------------------------------------------
  // Generated by host/filter_reference.py --emit-tb (float gold model, spec
  // 5.2-5.3).  Do not hand-edit: regenerate instead.
  // 4-pole -3 dB point at res=0:
  localparam real F_MINUS3DB_CI96_HZ  = 69.5;      // 160 Hz one-pole fc
  localparam real F_MINUS3DB_CI192_HZ = 278.0;     // 640 Hz one-pole fc
  localparam real F_MINUS3DB_CI288_HZ = 1120.0;    // 2560 Hz one-pole fc
  // Peak gain at res=255 (K=3.75); spec 5.2 expects +14.0..+15.2 dB:
  localparam real PEAK_DB_CI48_RES255  = 14.67;    // at 79 Hz
  localparam real PEAK_DB_CI192_RES255 = 14.67;    // at 629 Hz
  localparam real PEAK_DB_CI336_RES255 = 14.67;    // at 5038 Hz

  logic clk = 0, rst_n = 0, sample_ce = 0;
  logic signed [15:0] audio_in = 0;
  logic [11:0] ci  = 12'd192;
  logic [7:0]  res = 8'd0;
  logic signed [15:0] audio_out;
  logic out_valid;

  v2_ladder_lp dut (
      .clk       (clk),
      .rst_n     (rst_n),
      .sample_ce (sample_ce),
      .audio_in  (audio_in),
      .ci        (ci),
      .res       (res),
      .audio_out (audio_out),
      .out_valid (out_valid)
  );

  always #5 clk = ~clk;

  int checks = 0;
  int errors = 0;

  // --------------------------------------------------------------- utilities
  function automatic int rnd(input real x);
    rnd = (x >= 0.0) ? $rtoi(x + 0.5) : -$rtoi(-x + 0.5);
  endfunction

  // One-pole design frequency of a cutoff index, spec 5.3: 40 Hz * 2**(ci/48).
  function automatic real fc_of(input int c);
    fc_of = 40.0 * $exp(0.6931471805599453 * c / 48.0);
  endfunction

  // Theoretical passband droop of the ladder, host/filter_reference.py dc_db().
  function automatic real dc_db(input int r);
    dc_db = 20.0 * $log10(65536.0 / (65536.0 + r * 960.0));
  endfunction

  task automatic reset_dut;
    begin
      rst_n = 1'b0; sample_ce = 1'b0; audio_in = 16'sd0;
      repeat (4) @(negedge clk);
      rst_n = 1'b1;
      repeat (2) @(negedge clk);
    end
  endtask

  task automatic idle(input int n);
    int j;
    for (j = 0; j < n; j = j + 1) @(negedge clk);
  endtask

  // One 48 kHz sample.  Waits out the rest of the previous sample first, so the
  // sample_ce pulses are exactly CEP clocks apart.
  task automatic step(input int xin, output int v);
    begin
      repeat (CEP - 2) @(negedge clk);
      audio_in = xin[15:0]; sample_ce = 1'b1;
      @(negedge clk); sample_ce = 1'b0;
      if (out_valid !== 1'b1) begin
        $display("FAIL out_valid did not pulse with sample_ce");
        errors = errors + 1;
      end
      v = audio_out;
    end
  endtask

  task automatic stepf(input real amp, input real f, input int n, output int v);
    begin
      repeat (CEP - 2) @(negedge clk);
      audio_in = rnd(amp * $sin(2.0 * PI * f * n / FS));
      sample_ce = 1'b1;
      @(negedge clk); sample_ce = 1'b0;
      if (out_valid !== 1'b1) begin
        $display("FAIL out_valid did not pulse with sample_ce");
        errors = errors + 1;
      end
      v = audio_out;
    end
  endtask

  // Settling time for a resonant point: 9 time constants of Q=29 (measured on
  // the float model) at f0, so the peak is read to better than 0.1%.
  function automatic int settle_res(input real f0);
    int s;
    s = $rtoi(9.0 * 29.0 * FS / (PI * f0));
    if (s < 2000) s = 2000;
    if (s > 60000) s = 60000;
    settle_res = s;
  endfunction

  function automatic int meas_len(input real f);
    int m;
    m = $rtoi(1.1 * FS / f) + 50;
    if (m < 200) m = 200;
    meas_len = m;
  endfunction

  task automatic expect_true(input logic cond, input string what);
    begin
      checks = checks + 1;
      if (!cond) begin
        $display("FAIL %0s", what);
        errors = errors + 1;
      end else begin
        $display("PASS %0s", what);
      end
    end
  endtask

  task automatic expect_i(input int got, input int want, input string what);
    begin
      checks = checks + 1;
      if (got !== want) begin
        $display("FAIL %0s: got %0d want %0d", what, got, want);
        errors = errors + 1;
      end else begin
        $display("PASS %0s: %0d", what, got);
      end
    end
  endtask

  task automatic expect_range_i(input int got, input int lo, input int hi, input string what);
    begin
      checks = checks + 1;
      if (got < lo || got > hi) begin
        $display("FAIL %0s: got %0d want %0d..%0d", what, got, lo, hi);
        errors = errors + 1;
      end else begin
        $display("PASS %0s: %0d in %0d..%0d", what, got, lo, hi);
      end
    end
  endtask

  task automatic expect_near(input real got, input real want, input real tol, input string what);
    begin
      checks = checks + 1;
      if (!(got > want - tol && got < want + tol)) begin
        $display("FAIL %0s: got %.3f want %.3f +-%.3f", what, got, want, tol);
        errors = errors + 1;
      end else begin
        $display("PASS %0s: %.3f (want %.3f +-%.2f)", what, got, want, tol);
      end
    end
  endtask

  // Steady-state peak gain in dB at f.  amp must be small enough that the
  // output never clips; 1000 leaves 7 dB of headroom on the +14.7 dB peak.
  task automatic measure_gain(input int ci_v, input int res_v, input real f,
                              input real amp, input int settle, input int meas,
                              output real db);
    int k, vv, pk;
    begin
      ci = ci_v[11:0]; res = res_v[7:0];
      reset_dut();
      for (k = 0; k < settle; k = k + 1) stepf(amp, f, k, vv);
      pk = 0;
      for (k = settle; k < settle + meas; k = k + 1) begin
        stepf(amp, f, k, vv);
        if (vv > pk) pk = vv;
        if (-vv > pk) pk = -vv;
      end
      db = (pk > 0) ? 20.0 * $log10(pk / amp) : -200.0;
    end
  endtask

  task automatic find_minus3(input int ci_v, input real f_lo, input real f_hi,
                             output real fout);
    real lo, hi, mid, g;
    int it;
    begin
      lo = f_lo; hi = f_hi;
      for (it = 0; it < 12; it = it + 1) begin
        mid = 0.5 * (lo + hi);
        measure_gain(ci_v, 0, mid, 8000.0, 1500, meas_len(mid), g);
        if (g > -3.0) lo = mid;
        else hi = mid;
      end
      fout = 0.5 * (lo + hi);
    end
  endtask

  // ------------------------------------------------------------- test program
  int   v0, v1, k, n, prev, maxstep, wa, mag;
  int   peak_e, peak_l, flat, bad;
  real  f_meas, g_abs, peaks [0:3];
  real  u48, u192, u336, umin, umax;

  initial begin
    // 1. Latency: the response to a sample appears after the NEXT sample_ce,
    // not on the same one.  ci=423 makes the first impulse-response sample
    // G^4 * x = 0.249 * 8000 = 1993 rather than a rounding residue.
    ci = 12'd423; res = 8'd0;
    reset_dut();
    step(0, v0); step(0, v0);
    step(8000, v0);
    step(0, v1);
    expect_i(v0, 0, "an impulse is not published on its own sample_ce");
    expect_range_i(v1, 1800, 2200, "the first response sample is G^4 x one sample_ce later");

    // 2. The -3 dB points at res=0 match the float model within 15%.
    find_minus3(96,  F_MINUS3DB_CI96_HZ * 0.40,  F_MINUS3DB_CI96_HZ * 2.5, f_meas);
    expect_near(f_meas, F_MINUS3DB_CI96_HZ, F_MINUS3DB_CI96_HZ * 0.15,
                "-3 dB of ci=96");
    find_minus3(192, F_MINUS3DB_CI192_HZ * 0.40, F_MINUS3DB_CI192_HZ * 2.5, f_meas);
    expect_near(f_meas, F_MINUS3DB_CI192_HZ, F_MINUS3DB_CI192_HZ * 0.15,
                "-3 dB of ci=192");
    find_minus3(288, F_MINUS3DB_CI288_HZ * 0.40, F_MINUS3DB_CI288_HZ * 2.5, f_meas);
    expect_near(f_meas, F_MINUS3DB_CI288_HZ, F_MINUS3DB_CI288_HZ * 0.15,
                "-3 dB of ci=288");

    // 3. Resonance is monotone measured ABOVE DC.  res=0 has its maximum at DC,
    // so that point is read at 5 Hz; the rest at their measured peak frequency
    // (host/filter_reference.py peak_freq: 437.3 / 561.9 / 629.0 Hz).
    measure_gain(192, 0, 5.0, 8000.0, 1500, meas_len(5.0), g_abs);
    peaks[0] = g_abs - dc_db(0);
    measure_gain(192, 85, 437.3, 1000.0, settle_res(437.3), meas_len(437.3), g_abs);
    peaks[1] = g_abs - dc_db(85);
    measure_gain(192, 170, 561.9, 1000.0, settle_res(561.9), meas_len(561.9), g_abs);
    peaks[2] = g_abs - dc_db(170);
    measure_gain(192, 255, 629.0, 1000.0, settle_res(629.0), meas_len(629.0), g_abs);
    peaks[3] = g_abs - dc_db(255);
    expect_near(peaks[0], 0.0, 2.0, "resonance over DC at res=0");
    expect_near(peaks[1], 3.5, 2.0, "resonance over DC at res=85");
    expect_near(peaks[2], 11.1, 2.0, "resonance over DC at res=170");
    expect_near(peaks[3], 28.2, 2.0, "resonance over DC at res=255");
    expect_true(peaks[0] < peaks[1] && peaks[1] < peaks[2] && peaks[2] < peaks[3],
                "resonance over DC rises with res");

    // 4. Resonance is uniform in cutoff: the absolute res=255 peak at ci=48,
    // 192 and 336 differs by at most 3 dB (a ZDF property, not a ladder one).
    measure_gain(48, 255, 78.6, 1000.0, settle_res(78.6), meas_len(78.6), u48);
    measure_gain(192, 255, 629.0, 1000.0, settle_res(629.0), meas_len(629.0), u192);
    measure_gain(336, 255, 5038.0, 1000.0, settle_res(5038.0), meas_len(5038.0), u336);
    expect_near(u48, PEAK_DB_CI48_RES255, 2.0, "res=255 peak at ci=48");
    expect_near(u192, PEAK_DB_CI192_RES255, 2.0, "res=255 peak at ci=192");
    expect_near(u336, PEAK_DB_CI336_RES255, 2.0, "res=255 peak at ci=336");
    umin = u48; umax = u48;
    if (u192 < umin) umin = u192;
    if (u192 > umax) umax = u192;
    if (u336 < umin) umin = u336;
    if (u336 > umax) umax = u336;
    expect_true((umax - umin) <= 3.0, "res=255 peak is uniform in cutoff within 3 dB");

    // 5a. No divergence under drive.  Every ci 0..423 x res {0,128,255}, 2000
    // samples each, driven at the design cutoff where the loop is most excited.
    // The output must stay inside int16 and the state envelope must not grow.
    // (No sample-to-sample jump check here: at ci=423 the drive itself is 18 kHz,
    // where a legitimate full-scale sine moves 77000 LSB between samples.)
    bad = 0;
    for (n = 0; n <= 423; n = n + 1) begin
      for (k = 0; k < 3; k = k + 1) begin
        ci = n[11:0]; res = (k == 0) ? 8'd0 : ((k == 1) ? 8'd128 : 8'd255);
        reset_dut();
        peak_e = 0; peak_l = 0;
        for (v0 = 0; v0 < 2000; v0 = v0 + 1) begin
          stepf(32767.0, fc_of(n), v0, v1);
          if (v1 > 32767 || v1 < -32768) bad = bad + 1;
          wa = $signed(dut.w4);
          mag = (wa >= 0) ? wa : -wa;
          if (v0 < 1000) begin
            if (mag > peak_e) peak_e = mag;
          end else begin
            if (mag > peak_l) peak_l = mag;
          end
        end
        if (peak_l > 4 * peak_e + 20000) bad = bad + 1;
        if (peak_l > 20000000) bad = bad + 1;
      end
    end
    expect_i(bad, 0, "no divergence over ci 0..423 x res 0/128/255");

    // 5b. The definitive divergence probe: with NO input after one impulse there
    // is nothing to sustain the loop, so a stable filter can only ring DOWN.  A
    // K above Kcrit would grow instead.  ci=0 rings longest (Q=29 at 18 Hz), so
    // 3000 samples covers the slow corner as well as the fast ones.
    bad = 0;
    for (k = 0; k < 5; k = k + 1) begin
      n = (k == 0) ? 0 : ((k == 1) ? 96 : ((k == 2) ? 192 : ((k == 3) ? 336 : 423)));
      ci = n[11:0]; res = 8'd255;
      reset_dut();
      step(32767, v1);
      peak_e = 0; peak_l = 0; v0 = 0;
      for (v0 = 0; v0 < 1000; v0 = v0 + 1) begin
        step(0, v1);
        wa = $signed(dut.w4);
        mag = (wa >= 0) ? wa : -wa;
        if (mag > peak_e) peak_e = mag;
      end
      for (v0 = 0; v0 < 1000; v0 = v0 + 1) begin
        step(0, v1);
        wa = $signed(dut.w4);
        mag = (wa >= 0) ? wa : -wa;
        if (mag > peak_l) peak_l = mag;
      end
      if (peak_l > peak_e + peak_e / 20 + 1000) bad = bad + 1;
      for (v0 = 0; v0 < 1000; v0 = v0 + 1) begin
        step(0, v1);
        wa = $signed(dut.w4);
        mag = (wa >= 0) ? wa : -wa;
        if (mag > peak_l + peak_l / 20 + 1000) bad = bad + 1;
      end
    end
    expect_i(bad, 0, "the ringing decays with no input at five cutoffs, res=255");

    // 6. Saturation does not wrap.  Full scale at the resonant frequency asks
    // for +14.7 dB, so the output must be a flat-topped square with no jump
    // anywhere near the 65536 an int16 wrap would produce.
    ci = 12'd192; res = 8'd255;
    reset_dut();
    prev = 0; maxstep = 0; flat = 0;
    for (k = 0; k < 30000; k = k + 1) begin
      stepf(32767.0, 629.0, k, v1);
      if (v1 >= 32767 || v1 <= -32768) flat = flat + 1;
      if (k > 0) begin
        if ((v1 - prev) > maxstep) maxstep = v1 - prev;
        if ((prev - v1) > maxstep) maxstep = prev - v1;
      end
      prev = v1;
    end
    expect_true(flat > 1000, "full scale at res=255 clips into a flat top");
    expect_true(maxstep < 40000, "the clipped output never wraps");

    // 7. Nothing moves except on sample_ce.  After a sample the output must hold
    // the same value for the whole gap, and out_valid must be low for it.
    ci = 12'd192; res = 8'd128;
    reset_dut();
    stepf(9000.0, 300.0, 0, v0);
    prev = v0;
    bad = 0;
    for (k = 0; k < CEP - 3; k = k + 1) begin
      @(negedge clk);
      if (audio_out !== prev[15:0]) bad = bad + 1;
      if (out_valid !== 1'b0) bad = bad + 1;
    end
    expect_i(bad, 0, "audio_out and out_valid are quiet between two sample_ce pulses");

    if (errors != 0)
      $fatal(1, "tb_filter_ladder: %0d of %0d checks failed", errors, checks);
    $display("PASS tb_filter_ladder: %0d checks over the seven claims of task 5", checks);
    $finish;
  end

endmodule
