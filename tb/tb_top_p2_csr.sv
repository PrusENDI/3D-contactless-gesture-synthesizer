`timescale 1ns/1ps
// Top-level CSR gate for the six P2a registers (plan 2026-11-01 P2a, Task 2).
//
// Everything is driven through the real UART command path of mgc3130_v2_top, at
// the same 40 Mbaud the wavetable testbench uses, and every assertion reads the
// 22-byte reply the link actually serialises (SOF, type, sequence, data, error).
// The five things pinned here:
//   1. the documented reset values of 0x40/0x44/0x84/0x88/0x8C/0x90;
//   2. a write/read round trip of 0x40 (ci 0xC5, res 0x10, enable 1);
//   3. the contract clamp: ci 4095 -> 423, FX_C 0xFFFF_FFFF -> 0x7FFF_7333;
//   4. 0x9C (P2b) still answers BAD_ADDRESS instead of being half implemented;
//   5. the write mask and the 2.0 volume ceiling.
//
// The build-time FX defaults are FX_ENABLE(0) FX_LEVEL(0), so 0x84 resets to
// gain 1.0 / level 0 / enable 0 = 0x0001_0000 (spec 11.2 item 2).  The board
// build compiles FX_ENABLE(1) FX_LEVEL(1) and therefore resets to 0x0015_0000.
module tb_top_p2_csr;
  import v2_contract_pkg::*;

  logic clk_50m = 1'b0, uart_rx = 1'b1;
  tri mgc_sda, mgc_scl, mgc_ts, mgc_mclr;
  wire uart_tx, pcm5102a_bck, pcm5102a_lrck, pcm5102a_din;

  logic [7:0] inject_value;
  integer i, guard;
  logic [15:0] crc;
  integer seq_counter = 0;
  logic [7:0] last_seq;

  // Reply bytes as they leave the link, captured at the link/uart_tx handshake.
  // Decoding here instead of poking rsp_error is what makes a NACK generated by
  // the link itself (0x9C, out-of-mask data) observable at all: those replies
  // never pass through the top's rsp_* registers.
  logic [7:0] reply [0:21];
  integer reply_len = 0;

  always #5 clk_50m = ~clk_50m;
  GSR GSR(.GSRI(1'b1));

  mgc3130_v2_top #(.USE_MGC_READER(0), .USE_POTTS(1), .UART_BAUD(40_000_000),
                   .POTTS_HORIZON(32), .V2_DEBUG_CSR(1),
                   .FX_ENABLE(0), .FX_LEVEL(0)) dut (
    .clk_50m(clk_50m), .mgc_sda(mgc_sda), .mgc_scl(mgc_scl), .mgc_ts(mgc_ts),
    .mgc_mclr(mgc_mclr), .uart_rx(uart_rx), .uart_tx(uart_tx),
    .pcm5102a_bck(pcm5102a_bck), .pcm5102a_lrck(pcm5102a_lrck), .pcm5102a_din(pcm5102a_din)
  );

  always @(posedge clk_50m) begin
    if (dut.v2_tx_valid && dut.v2_tx_ready) begin
      if (reply_len < 22) reply[reply_len] = dut.v2_tx_byte;
      reply_len = reply_len + 1;
    end
  end

  function automatic [15:0] crc_byte(input [15:0] crc_in, input [7:0] value);
    reg [15:0] c;
    integer b;
    begin
      c = crc_in ^ {value, 8'h00};
      for (b = 0; b < 8; b = b + 1)
        c = c[15] ? ((c << 1) ^ 16'h1021) : (c << 1);
      crc_byte = c;
    end
  endfunction

  function automatic [31:0] reply_word;
    reply_word = {reply[14], reply[15], reply[16], reply[17]};
  endfunction

  task automatic inject_byte(input [7:0] value);
    begin
      inject_value = value;
      force dut.uart_byte = inject_value;
      force dut.uart_byte_valid = 1'b1;
      @(posedge clk_50m);
      #1;
      force dut.uart_byte_valid = 1'b0;
      @(posedge clk_50m);
      #1;
      release dut.uart_byte_valid;
      release dut.uart_byte;
    end
  endtask

  // One 11-byte control frame, then wait for its 22-byte reply.  The link holds
  // one outstanding transaction, so the frame is not started until the previous
  // reply has finished leaving the wire; a frame started early is dropped.
  task automatic send_frame(input [7:0] op, input [7:0] address, input [31:0] data);
    reg [7:0] b [0:10];
    reg [15:0] c;
    integer k;
    begin
      last_seq = seq_counter[7:0];
      seq_counter = seq_counter + 1;
      b[0] = 8'ha5; b[1] = 8'h02; b[2] = op; b[3] = address; b[4] = last_seq;
      b[5] = data[31:24]; b[6] = data[23:16]; b[7] = data[15:8]; b[8] = data[7:0];
      c = 16'hffff;
      for (k = 0; k < 9; k = k + 1) c = crc_byte(c, b[k]);
      b[9] = c[15:8]; b[10] = c[7:0];
      guard = 0;
      while ((dut.v2_tx_valid || dut.uart_tx_busy) && guard < 200000) begin
        @(posedge clk_50m);
        guard = guard + 1;
      end
      if (guard >= 200000) $fatal(1, "the previous reply never finished");
      reply_len = 0;
      for (k = 0; k < 11; k = k + 1) inject_byte(b[k]);
      guard = 0;
      while (reply_len < 22 && guard < 200000) begin
        @(posedge clk_50m);
        guard = guard + 1;
      end
      if (reply_len != 22) $fatal(1, "no 22-byte reply for op=0x%02h addr=0x%02h", op, address);
      guard = 0;
      while ((dut.v2_tx_valid || dut.uart_tx_busy) && guard < 200000) begin
        @(posedge clk_50m);
        guard = guard + 1;
      end
      if (dut.v2_tx_valid || dut.uart_tx_busy) $fatal(1, "V2 UART response did not drain");
      repeat (2) @(posedge clk_50m);
    end
  endtask

  task automatic expect_reply(input [7:0] ack, input [7:0] err, input [511:0] what);
    begin
      if (reply[0] !== V2_TELEMETRY_SOF || reply[1] !== V2_VERSION)
        $fatal(1, "%s: malformed reply header sof=0x%02h ver=0x%02h",
               what, reply[0], reply[1]);
      if (reply[4] !== last_seq)
        $fatal(1, "%s: reply sequence 0x%02h, expected 0x%02h", what, reply[4], last_seq);
      if (reply[2] !== ack)
        $fatal(1, "%s: reply type 0x%02h, expected 0x%02h (error 0x%02h)",
               what, reply[2], ack, reply[19]);
      if (reply[19] !== err)
        $fatal(1, "%s: reply error 0x%02h, expected 0x%02h", what, reply[19], err);
    end
  endtask

  task automatic expect_csr(input [7:0] address, input [31:0] want, input [511:0] what);
    begin
      send_frame(V2_OP_READ, address, 32'd0);
      expect_reply(V2_TLM_ACK, V2_ERR_NONE, what);
      if (reply_word() !== want)
        $fatal(1, "%s: CSR 0x%02h read 0x%08h, expected 0x%08h",
               what, address, reply_word(), want);
      $display("PASS %s = 0x%08h", what, reply_word());
    end
  endtask

  task automatic write_csr(input [7:0] address, input [31:0] data, input [511:0] what);
    begin
      send_frame(V2_OP_WRITE, address, data);
      expect_reply(V2_TLM_ACK, V2_ERR_NONE, what);
      $display("PASS %s accepted", what);
    end
  endtask

  initial begin : run_tb
    repeat (40) @(posedge clk_50m);
    if (!dut.rst_sys_n || !dut.pll_locked) $fatal(1, "reset/PLL did not release");

    // Read-path self test: if the reply decoder were wrong every later result is
    // the bench's fault, not the DUT's.
    expect_csr(8'hB0, 32'h5A5A_0003, "read path self test (0xB0 constant)");

    // ---- 1. Reset values -------------------------------------------------
    expect_csr(V2_CSR_FILTER, 32'h0000_0000, "0x40 filter reset (bypass)");
    expect_csr(V2_CSR_LFO,    32'h0000_0000, "0x44 lfo reset (off)");
    expect_csr(V2_CSR_FX_A,   32'h0001_0000, "0x84 fx_a reset (gain 1.0, level 0, enable 0)");
    expect_csr(V2_CSR_FX_B,   32'hFFFF_0000, "0x88 fx_b reset (cutoff passthrough)");
    expect_csr(V2_CSR_FX_C,   32'h0000_0000, "0x8C fx_c reset");
    expect_csr(V2_CSR_VOLUME, 32'h0001_0000, "0x90 volume reset (unity)");

    // ---- 2. Write/read round trip ---------------------------------------
    write_csr(V2_CSR_FILTER, 32'h0101_00C5, "0x40 = 0x010100C5");
    expect_csr(V2_CSR_FILTER, 32'h0101_00C5, "0x40 round trip (ci 0xC5, res 0x10, enable 1)");
    if (dut.ci_reg !== 12'h0C5 || dut.res_reg !== 8'h10 || dut.filter_en !== 1'b1)
      $fatal(1, "0x40 unpacking: ci=0x%03h res=0x%02h en=%0b", dut.ci_reg, dut.res_reg, dut.filter_en);
    $display("PASS 0x40 unpacking: ci=0x%03h res=0x%02h enable=%0b",
             dut.ci_reg, dut.res_reg, dut.filter_en);

    // ---- 3. The contract clamp ------------------------------------------
    write_csr(V2_CSR_FILTER, 32'h0000_0FFF, "0x40 ci = 4095");
    expect_csr(V2_CSR_FILTER, 32'h0000_01A7, "0x40 ci clamps 4095 -> 423 (0x1A7)");
    if (dut.ci_reg !== 12'd423) $fatal(1, "0x40 unpacked ci=0x%03h, expected 423", dut.ci_reg);
    write_csr(V2_CSR_FX_C, 32'hFFFF_FFFF, "0x8C = 0xFFFFFFFF");
    expect_csr(V2_CSR_FX_C, 32'h7FFF_7333, "0x8C feedback clamps to 0.9, reverb_mix to 1.0");
    if (dut.fx_feedback_reg !== 16'h7333 || dut.fx_reverb_reg !== 16'h7FFF)
      $fatal(1, "0x8C unpacking: feedback=0x%04h reverb=0x%04h",
             dut.fx_feedback_reg, dut.fx_reverb_reg);
    $display("PASS 0x8C unpacking: feedback=0x%04h reverb=0x%04h",
             dut.fx_feedback_reg, dut.fx_reverb_reg);

    // ---- 4. P2b is not implemented yet: 0x9C must still be rejected ------
    send_frame(V2_OP_WRITE, 8'h9C, 32'h0000_0001);
    if (reply[2] !== V2_TLM_NACK)
      $fatal(1, "0x9C write was not NACKed (type=0x%02h err=0x%02h)", reply[2], reply[19]);
    if (reply[19] !== V2_ERR_BAD_ADDRESS)
      $fatal(1, "0x9C write NACKed with 0x%02h, expected BAD_ADDRESS 0x02", reply[19]);
    $display("PASS 0x9C write is still NACKed with BAD_ADDRESS (0x02)");

    // ---- 5. Write mask and the 2.0 volume ceiling -----------------------
    // Bits outside the mask are not a clamp input: v2_csr_data_valid() still
    // refuses them (Global Constraints), so 0xFFFF_FFFF is a BAD_DATA NACK and
    // the register keeps its old value.
    send_frame(V2_OP_WRITE, V2_CSR_VOLUME, 32'hFFFF_FFFF);
    if (reply[2] !== V2_TLM_NACK || reply[19] !== V2_ERR_BAD_DATA)
      $fatal(1, "0x90 out-of-mask write: type=0x%02h err=0x%02h, expected NACK 0x07",
             reply[2], reply[19]);
    $display("PASS 0x90 write with out-of-mask bits is NACKed with BAD_DATA (0x07)");
    expect_csr(V2_CSR_VOLUME, 32'h0001_0000, "0x90 is unchanged by the rejected write");
    // The largest in-mask value then clamps to 2.0 and keeps no higher bit.
    write_csr(V2_CSR_VOLUME, 32'h0003_FFFF, "0x90 = 0x0003FFFF");
    expect_csr(V2_CSR_VOLUME, 32'h0002_0000, "0x90 clamps to 2.0 (0x20000)");
    if (dut.volume_reg !== 32'h0002_0000)
      $fatal(1, "0x90 register holds 0x%08h, expected 0x00020000", dut.volume_reg);

    // 0x44 must latch as a whole word too, so the Task 6 unpacking has a value.
    write_csr(V2_CSR_LFO, 32'h1BDB_4E20, "0x44 = 0x1BDB4E20");
    expect_csr(V2_CSR_LFO, 32'h1BDB_4E20, "0x44 round trip");
    if (dut.lfo_rate_mhz !== 16'd20000 || dut.lfo_depth !== 8'hDB ||
        dut.lfo_en !== 1'b1 || dut.lfo_retrig !== 1'b1 ||
        dut.lfo_unipolar !== 1'b0 || dut.lfo_wave !== 3'd3)
      $fatal(1, "0x44 unpacking: rate=%0d depth=0x%02h en=%0b rt=%0b uni=%0b wave=%0d",
             dut.lfo_rate_mhz, dut.lfo_depth, dut.lfo_en, dut.lfo_retrig,
             dut.lfo_unipolar, dut.lfo_wave);
    $display("PASS 0x44 unpacking: rate=%0d depth=0x%02h wave=%0d",
             dut.lfo_rate_mhz, dut.lfo_depth, dut.lfo_wave);

    $display("PASS tb_top_p2_csr: six P2a CSRs latch, clamp and read back");
    $finish;
  end

  initial begin : timeout
    #5_000_000;
    $fatal(1, "tb_top_p2_csr timeout");
  end
endmodule
